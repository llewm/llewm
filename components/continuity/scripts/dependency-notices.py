#!/usr/bin/env python3
"""Collect shipped Go dependency notices; --check refuses a stale notice bundle."""
import argparse
import json
import os
from pathlib import Path
import re
import subprocess


ROOT = Path(__file__).resolve().parents[3]
OUTPUT = ROOT / "components/continuity/THIRD_PARTY_NOTICES.txt"
TARGETS = ("linux/amd64", "linux/arm64", "darwin/amd64", "darwin/arm64",
           "windows/amd64", "windows/arm64")
COMMANDS = {"continuity": "llewm", "reporting": "llewm-report",
            "action-control": "action-control"}


def objects(raw):
    decoder = json.JSONDecoder()
    while raw.strip():
        raw = raw.lstrip()
        value, end = decoder.raw_decode(raw)
        yield value
        raw = raw[end:]


def generate():
    modules = {}
    for component, command in COMMANDS.items():
        cwd = ROOT / "components" / component
        for target in TARGETS:
            system, arch = target.split("/")
            env = dict(os.environ, GOOS=system, GOARCH=arch, CGO_ENABLED="0", GOWORK="off")
            raw = subprocess.check_output(
                ["go", "list", "-deps", "-json", "./cmd/" + command], cwd=cwd, env=env, text=True)
            for package in objects(raw):
                module = package.get("Module")
                if module and not module.get("Main"):
                    if module.get("Replace"):
                        raise SystemExit("Review replaced module before distributing: " + module["Path"])
                    modules[(module["Path"], module["Version"])] = Path(module["Dir"])
    parts = ["Third-party notices for Llewm source-built commands\n\n"
             "Generated by components/continuity/scripts/dependency-notices.py.\n"
             "Includes the union of non-test dependencies for llewm, llewm-report\n"
             "and action-control on the six preview platforms with CGO disabled.\n"
             "Upstream notices remain under their respective terms; Llewm's MIT\n"
             "license does not replace them. Review again when dependencies change.\n"]
    goroot = Path(subprocess.check_output(["go", "env", "GOROOT"], text=True).strip())
    for name in ("LICENSE", "PATENTS"):
        path = goroot / name
        if path.is_file():
            parts.append("\n=== Go runtime / " + name + " ===\n\n" + path.read_text().rstrip() + "\n")
    for (module, version), directory in sorted(modules.items()):
        # Keep nested notices too: libc, for example, embeds separately licensed code.
        paths = sorted(p for p in directory.rglob("*") if p.is_file()
                       and re.fullmatch(r"(?:.*[-_])?(?:LICENSE|LICENCE|COPYING|COPYRIGHT|NOTICE)(?:[._-].*)?",
                                        p.name, re.IGNORECASE)
                       and p.suffix not in (".go", ".c", ".h")
                       and "testdata" not in p.relative_to(directory).parts)
        if not paths:
            raise SystemExit("Missing dependency notice: " + module + "@" + version)
        for path in paths:
            parts.append("\n=== " + module + "@" + version + " / "
                         + path.relative_to(directory).as_posix() + " ===\n\n"
                         + path.read_text().rstrip() + "\n")
    return "".join(parts)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not OUTPUT.is_file() or OUTPUT.read_text() != content:
            raise SystemExit("Dependency notices are stale; regenerate and review them.")
        print("Dependency notices are current.")
    else:
        OUTPUT.write_text(content)
        print("Wrote " + str(OUTPUT.relative_to(ROOT)))
