package roadmap

import (
	"context"
	"crypto/sha256"
	"encoding/hex"
	"encoding/json"
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"
)

const (
	RendererName       = "continuity-roadmap-markdown"
	RendererVersion    = 2
	maxProjectionLinks = 512
	maxProjectionBytes = 4 << 20
)

var RendererHash = hashBytes([]byte("continuity-roadmap-markdown:v2:generated-header+grouped-nodes+tracks+authoritative-plans+relationships+triggers"))

type canonicalGraph struct {
	Nodes          []SnapshotNode         `json:"nodes"`
	Bindings       []SnapshotBinding      `json:"bindings"`
	Relationships  []SnapshotRelationship `json:"relationships"`
	Tracks         []Track                `json:"tracks"`
	ReviewTriggers []SnapshotTrigger      `json:"review_triggers"`
}

func (service Service) Snapshot(ctx context.Context, projectID string) (GraphSnapshot, error) {
	if _, err := text("project ID", projectID, true); err != nil {
		return GraphSnapshot{}, err
	}
	nodes, err := service.currentNodes(ctx, projectID)
	if err != nil {
		return GraphSnapshot{}, err
	}
	links, truncated, err := service.currentNodeLinks(ctx, projectID, maxProjectionLinks)
	if err != nil {
		return GraphSnapshot{}, err
	}
	if truncated {
		return GraphSnapshot{}, fmt.Errorf("current roadmap relationships exceed %d-item projection limit", maxProjectionLinks)
	}
	bindings, err := service.currentBindings(ctx, projectID)
	if err != nil {
		return GraphSnapshot{}, err
	}
	status, err := service.Status(ctx, projectID)
	if err != nil {
		return GraphSnapshot{}, err
	}

	graph := canonicalGraph{
		Nodes:          make([]SnapshotNode, 0, len(nodes)),
		Bindings:       make([]SnapshotBinding, 0, len(bindings)),
		Relationships:  make([]SnapshotRelationship, 0, len(links)),
		ReviewTriggers: snapshotTriggers(reviewTriggers(status)),
	}
	for _, node := range nodes {
		graph.Nodes = append(graph.Nodes, SnapshotNode{ID: node.ID, Revision: node.Revision, Title: node.Title, Status: node.Status, Priority: node.Priority, Kind: node.Kind, TargetDate: node.TargetDate, TargetRelease: node.TargetRelease, TargetHorizon: node.TargetHorizon, EvidenceRefs: node.EvidenceRefs, SourcePath: node.SourcePath, SourceRef: node.SourceRef})
	}
	for _, binding := range bindings {
		graph.Bindings = append(graph.Bindings, SnapshotBinding{NodeID: binding.NodeID, NodeRevision: binding.NodeRevision, Path: binding.Path, PathKind: binding.PathKind, Relationship: binding.Relationship})
	}
	for _, link := range links {
		graph.Relationships = append(graph.Relationships, SnapshotRelationship{NodeID: link.NodeID, NodeRevision: link.NodeRevision, Relationship: link.Relationship, TargetNodeID: link.TargetNodeID})
	}
	sort.Slice(graph.Bindings, func(i, j int) bool {
		a, b := graph.Bindings[i], graph.Bindings[j]
		if a.NodeID != b.NodeID {
			return a.NodeID < b.NodeID
		}
		if a.Path != b.Path {
			return a.Path < b.Path
		}
		if a.Relationship != b.Relationship {
			return a.Relationship < b.Relationship
		}
		if a.PathKind != b.PathKind {
			return a.PathKind < b.PathKind
		}
		return a.NodeRevision < b.NodeRevision
	})
	sort.Slice(graph.Relationships, func(i, j int) bool {
		a, b := graph.Relationships[i], graph.Relationships[j]
		if a.NodeID != b.NodeID {
			return a.NodeID < b.NodeID
		}
		if a.Relationship != b.Relationship {
			return a.Relationship < b.Relationship
		}
		if a.TargetNodeID != b.TargetNodeID {
			return a.TargetNodeID < b.TargetNodeID
		}
		return a.NodeRevision < b.NodeRevision
	})
	graph.Tracks, _ = roadmapTracks(nodes, links, len(nodes))
	encoded, err := json.Marshal(graph)
	if err != nil {
		return GraphSnapshot{}, err
	}
	return GraphSnapshot{
		SchemaVersion: SchemaVersion, ProjectID: projectID, ProjectName: service.ProjectName,
		GraphHash: hashBytes(encoded), Nodes: graph.Nodes,
		Bindings: graph.Bindings, Relationships: graph.Relationships, Tracks: graph.Tracks,
		ReviewTriggers: graph.ReviewTriggers,
	}, nil
}

func (service Service) Render(ctx context.Context, projectID string) (Projection, error) {
	snapshot, err := service.Snapshot(ctx, projectID)
	if err != nil {
		return Projection{}, err
	}
	return renderSnapshot(snapshot)
}

func renderSnapshot(snapshot GraphSnapshot) (Projection, error) {
	body := renderBody(snapshot)
	if len([]byte(body)) > maxProjectionBytes {
		return Projection{}, fmt.Errorf("roadmap projection exceeds 4 MiB limit")
	}
	contentHash := hashBytes([]byte(body))
	projectName := markdownText(snapshot.ProjectName)
	if projectName == "" {
		projectName = snapshot.ProjectID
	}
	header := fmt.Sprintf("<!-- Generated by %s v%d; DO NOT EDIT. -->\n\n# %s roadmap\n\n- Project: `%s`\n- Graph hash: `%s`\n- Renderer: `%s` v%d (`%s`)\n- Content hash: `%s`\n\n", RendererName, RendererVersion, projectName, snapshot.ProjectID, snapshot.GraphHash, RendererName, RendererVersion, RendererHash, contentHash)
	markdown := header + body
	return Projection{SchemaVersion: SchemaVersion, ProjectID: snapshot.ProjectID, GraphHash: snapshot.GraphHash, RendererName: RendererName, RendererVersion: RendererVersion, RendererHash: RendererHash, ContentHash: contentHash, Markdown: markdown}, nil
}

func (service Service) CheckProjection(ctx context.Context, projectID, relative string) (ProjectionCheck, error) {
	relative, err := relativePath("projection path", relative)
	if err != nil {
		return ProjectionCheck{}, err
	}
	projection, err := service.Render(ctx, projectID)
	if err != nil {
		return ProjectionCheck{}, err
	}
	result := ProjectionCheck{SchemaVersion: SchemaVersion, ProjectID: projectID, Path: relative, State: "missing", ExpectedHash: hashBytes([]byte(projection.Markdown)), GraphHash: projection.GraphHash, RendererHash: projection.RendererHash, Disclaimer: "Check is read-only and byte-exact; manual edits are reported as drift and are never parsed into roadmap records or overwritten."}
	path := filepath.Join(service.Root, filepath.FromSlash(relative))
	info, err := os.Lstat(path)
	if os.IsNotExist(err) {
		return result, nil
	}
	if err != nil {
		return ProjectionCheck{}, err
	}
	if info.Mode()&os.ModeSymlink != 0 || !info.Mode().IsRegular() || info.Size() > maxProjectionBytes {
		return ProjectionCheck{}, fmt.Errorf("projection path %s must be a non-symlink regular file no larger than 4 MiB", relative)
	}
	data, err := os.ReadFile(path)
	if err != nil {
		return ProjectionCheck{}, err
	}
	result.ActualHash = hashBytes(data)
	result.State = "drifted"
	if string(data) == projection.Markdown {
		result.State = "current"
	}
	return result, nil
}

func renderBody(snapshot GraphSnapshot) string {
	var out strings.Builder
	sections := []struct {
		name     string
		statuses map[string]bool
	}{
		{"Active tracks", map[string]bool{"active": true, "accepted": true}},
		{"Blocked work", map[string]bool{"blocked": true}},
		{"Future work", map[string]bool{"proposed": true}},
		{"Completed work", map[string]bool{"completed": true}},
		{"Deferred work", map[string]bool{"deferred": true}},
	}
	tracks := make(map[string]Track, len(snapshot.Tracks))
	for _, track := range snapshot.Tracks {
		tracks[track.Node.ID] = track
	}
	for _, section := range sections {
		out.WriteString("## " + section.name + "\n\n")
		count := 0
		for _, node := range snapshot.Nodes {
			if !section.statuses[node.Status] {
				continue
			}
			count++
			fmt.Fprintf(&out, "- `%s` — %s (priority %d, revision %d, status `%s`)\n", node.ID, markdownText(node.Title), node.Priority, node.Revision, node.Status)
			renderTrack(&out, tracks[node.ID])
		}
		if count == 0 {
			out.WriteString("_None._\n")
		}
		out.WriteByte('\n')
	}
	out.WriteString("## Relationships\n\n")
	if len(snapshot.Relationships) == 0 {
		out.WriteString("_None._\n")
	}
	for _, link := range snapshot.Relationships {
		fmt.Fprintf(&out, "- `%s` `%s` `%s`\n", link.NodeID, link.Relationship, link.TargetNodeID)
	}
	out.WriteString("\n## Review triggers\n\n")
	if len(snapshot.ReviewTriggers) == 0 {
		out.WriteString("_None._\n")
	}
	for _, trigger := range snapshot.ReviewTriggers {
		threshold := "n/a"
		if trigger.Threshold != nil {
			threshold = fmt.Sprint(*trigger.Threshold)
		}
		fmt.Fprintf(&out, "- `%s`: state `%s`, observation `%s`, threshold `%s`, routine `%s@%d`\n", trigger.Kind, trigger.State, trigger.Observation, threshold, trigger.RoutineID, trigger.RoutineRevision)
	}
	out.WriteString("\n")
	return out.String()
}

func markdownRefs(values []string) []string {
	result := make([]string, 0, len(values))
	for _, value := range values {
		result = append(result, markdownText(value))
	}
	return result
}

func snapshotTriggers(triggers []ReviewTrigger) []SnapshotTrigger {
	result := make([]SnapshotTrigger, 0, len(triggers))
	for _, trigger := range triggers {
		observation := "not_evaluated"
		if trigger.Threshold == nil && trigger.State == "due" {
			observation = "required"
		} else if trigger.Threshold != nil && trigger.Observed != nil {
			observation = "< threshold"
			if trigger.State == "due" {
				observation = ">= threshold"
			}
		}
		result = append(result, SnapshotTrigger{Kind: trigger.Kind, Threshold: trigger.Threshold, Observation: observation, State: trigger.State, RoutineID: trigger.RoutineID, RoutineRevision: trigger.RoutineRevision})
	}
	return result
}

func renderTrack(out *strings.Builder, track Track) {
	for _, group := range []struct {
		name   string
		values []NodeRef
	}{
		{"Parents", track.Parents}, {"Subtasks", track.Subtasks}, {"Dependencies", track.DependsOn},
		{"Unresolved dependencies", track.UnresolvedDependencies}, {"Blocked by", track.BlockedBy},
		{"Blocks", track.Blocks}, {"Parallel with", track.ParallelWith}, {"Explores", track.Explores},
	} {
		if len(group.values) == 0 {
			continue
		}
		values := make([]string, 0, len(group.values))
		for _, value := range group.values {
			values = append(values, fmt.Sprintf("`%s` (%s)", value.ID, value.Status))
		}
		fmt.Fprintf(out, "  - %s: %s\n", group.name, strings.Join(values, ", "))
	}
}

func markdownText(value string) string {
	return strings.ReplaceAll(strings.Join(strings.Fields(value), " "), "`", "\\`")
}

func hashBytes(value []byte) string {
	sum := sha256.Sum256(value)
	return hex.EncodeToString(sum[:])
}
